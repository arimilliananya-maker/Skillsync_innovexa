function student(input: StudentInput, hue: number): User {
  const handle = input.name.toLowerCase().split(' ')[0]
  return {
    email: `${handle}@skillsync.demo`,
    role: 'student',
    previousProjects: [],
    achievements: [],
    github: `https://github.com/${handle}-dev`,
    portfolio: `https://${handle}.portfolio.demo`,
    verified: true,
    status: 'active',
    joinedAt: daysAgo(120 - hue / 4),
    avatarHue: hue,
    ...input,
  }
}

